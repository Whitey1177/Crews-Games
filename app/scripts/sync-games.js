// Copies the games from ../public into games.js so they are packed inside the app (work offline).
// Run after changing a game:  node scripts/sync-games.js
const fs = require('fs'), path = require('path');
const pub = path.join(__dirname, '..', '..', 'public');
const pages = {home: 'index.html', merge: 'merge/index.html', jump: 'jump/index.html', adventure: 'adventure/index.html', privacy: 'privacy/index.html'};
let out = '// AUTO-GENERATED by scripts/sync-games.js — do not edit by hand.\nexport const PAGES = {\n';
for (const [k, f] of Object.entries(pages)) out += `  ${k}: ${JSON.stringify(fs.readFileSync(path.join(pub, f), 'utf8'))},\n`;
fs.writeFileSync(path.join(__dirname, '..', 'games.js'), out + '};\n');
console.log('games.js updated');
